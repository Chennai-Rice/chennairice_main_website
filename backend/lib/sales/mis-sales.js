// The MIS dashboard's "Sales" view (Nov 2026): the B2C and B2B tabs of the MIS sheet, with the BILL VALUE of each order,
// so the dashboard can rank managers and telesales by what they closed. Read-only, like mis.js.
//
// Columns are found by name (not position). A row is a SALE when it has a bill value above zero; a row marked
// "Sale completed" with no bill value is kept and flagged (missingBill) so it can be fixed in the sheet.

const norm = (h) => String(h ?? '').toLowerCase().replace(/[^a-z0-9]/g, '')
const clean = (v) => String(v ?? '').replace(/\s+/g, ' ').trim()

// field → header names; `exact` headers must equal; `last` takes the last matching column (the sheet has two "Quantity").
const FIELDS = {
  date: { names: ['date'], exact: true },
  telesales: { names: ['leadgeneratedby', 'generatedby', 'telesales', 'telecaller'] },
  brand: { names: ['brand', 'brandname'], exact: true }, // optional: the sales tabs have no Brand column yet
  type: { names: ['leadtype'], exact: true },
  source: { names: ['leadsource'], exact: true },
  name: { names: ['name', 'customername'], exact: true },
  phone: { names: ['contactnumber', 'mobilenumber', 'phone'] },
  city: { names: ['location', 'city'], exact: true },
  manager: { names: ['manager'], exact: true },
  asm: { names: ['asm'], exact: true },
  status: { names: ['status'], exact: true },
  product: { names: ['orderedproduct'] },
  kg: { names: ['kg'], exact: true },
  qty: { names: ['quantity'], exact: true, last: true },
  bill: { names: ['billvalue', 'billamount', 'invoicevalue'] },
  remark: { names: ['remarks', 'remark'], exact: true },
}

export function mapSalesColumns(headers) {
  const keys = headers.map(norm)
  const found = {}
  for (const [field, { names, exact, last }] of Object.entries(FIELDS)) {
    for (const name of names) {
      const hits = keys.map((k, i) => (k && (exact ? k === name : k === name || k.includes(name)) ? i : -1)).filter((i) => i >= 0)
      if (hits.length) {
        found[field] = last ? hits[hits.length - 1] : hits[0]
        break
      }
    }
  }
  return found
}

/** "₹ 3,550" → 3550; anything that is not a number (#REF!, text) → 0. */
export function money(v) {
  const t = String(v ?? '').replace(/[,₹\s]/g, '').replace(/^rs\.?/i, '')
  const n = /^-?\d+(\.\d+)?$/.test(t) ? Number(t) : 0
  return n > 0 ? n : 0
}

const MONTHS = { jan: 1, feb: 2, mar: 3, apr: 4, may: 5, jun: 6, jul: 7, aug: 8, sep: 9, oct: 10, nov: 11, dec: 12 }
function day(value) {
  const t = String(value ?? '').trim()
  let m = /^(\d{1,2})[-/.](\d{1,2})[-/.](\d{2,4})/.exec(t)
  if (m) return ymd(+m[3], +m[2], +m[1])
  m = /^(\d{4})[-/.](\d{1,2})[-/.](\d{1,2})/.exec(t)
  if (m) return ymd(+m[1], +m[2], +m[3])
  m = /^(\d{1,2})[ -]([A-Za-z]{3})[a-z]*[ ,-]+(\d{2,4})/.exec(t)
  if (m && MONTHS[m[2].toLowerCase()]) return ymd(+m[3], MONTHS[m[2].toLowerCase()], +m[1])
  return ''
}
function ymd(y, m, d) {
  if (y < 100) y += 2000
  return m >= 1 && m <= 12 && d >= 1 && d <= 31 && y >= 2000 && y <= 2100 ? `${y}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}` : ''
}

/** A person's name in one spelling: "MANSOOR" and "Mansoor" are the same telesales; #REF! and blanks are "Not assigned". */
function person(v) {
  const t = clean(v)
  if (!t || /^#|^(n\/?a|na|nil|-|none)$/i.test(t)) return 'Not assigned'
  // One spelling per person: "Sailesh", "SAILESH" and "SAilesh" are the same person, so every name is Title Case.
  return t.replace(/\s+/g, ' ').toLowerCase().replace(/\b[a-z]/g, (c) => c.toUpperCase())
}

/**
 * One tab (rows of text) as sale rows. `type` is 'B2B' or 'B2C' (the tab's name).
 * Returns { type, sheetTitle, mapping, missing, rows } or throws nothing: a tab with no usable header gives rows: [].
 */
export function buildSales(matrix, { type, sheetTitle = '' } = {}) {
  const grid = (matrix || []).map((r) => (Array.isArray(r) ? r.map((c) => String(c ?? '')) : []))
  const headerAt = grid.slice(0, 10).findIndex((r) => r.some((c) => /bill\s*value/i.test(c)) || r.some((c) => /generated\s*by/i.test(c)))
  if (headerAt < 0) return { type, sheetTitle, mapping: {}, missing: Object.keys(FIELDS), rows: [], error: `No header row with BILL VALUE or LEAD GENERATED BY in the ${type} tab.` }
  const headers = grid[headerAt].map(clean)
  const cols = mapSalesColumns(headers)
  const cell = (row, f) => (cols[f] == null ? '' : clean(row[cols[f]]))
  const rows = []
  for (const row of grid.slice(headerAt + 1)) {
    const name = cell(row, 'name')
    const phone = cell(row, 'phone')
    const bill = money(cell(row, 'bill'))
    if (!name && !phone && !bill) continue // the long run of empty template rows
    const date = day(cell(row, 'date'))
    const status = cell(row, 'status')
    const completed = /sale\s*completed|completed|delivered|closed won/i.test(status)
    rows.push({
      n: rows.length + 1,
      type,
      date,
      month: date ? date.slice(0, 7) : '',
      brand: clean(cell(row, 'brand')),
      telesales: person(cell(row, 'telesales')),
      manager: person(cell(row, 'manager')),
      asm: person(cell(row, 'asm')),
      source: clean(cell(row, 'source')).toUpperCase() || 'NOT SPECIFIED',
      name,
      phone,
      city: cell(row, 'city').startsWith('#') ? '' : cell(row, 'city'),
      product: cell(row, 'product'),
      kg: cell(row, 'kg'),
      qty: Number(cell(row, 'qty')) || 0,
      bill,
      status,
      sale: bill > 0,
      missingBill: completed && !(bill > 0),
      remark: cell(row, 'remark'),
    })
  }
  return {
    type,
    sheetTitle,
    mapping: Object.fromEntries(Object.entries(cols).map(([f, i]) => [f, headers[i]])),
    missing: Object.keys(FIELDS).filter((f) => cols[f] == null),
    rows,
  }
}
