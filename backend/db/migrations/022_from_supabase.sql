-- 022 — Everything that used to live in Supabase moves here, so the website
-- runs on Google Cloud alone: visitor analytics (the /admin dashboard), the
-- blog, its cover images, and the contact / bulk-order enquiries. Columns
-- match the Supabase tables so their rows copy across unchanged
-- (backend/db/copy-from-supabase.js). Access is the staff sign-in: the old
-- Supabase admin_users / blog_authors lists are replaced by staff roles.

-- ---------------------------------------------------------------- enquiries
create table if not exists contact_enquiries (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,
  email       text not null,
  phone       text not null,
  enquiry     text not null,
  status      text not null default 'new' check (status in ('new', 'contacted', 'closed')),
  notes       text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists bulk_order_enquiries (
  id                   uuid primary key default gen_random_uuid(),
  buyer_type           text not null check (buyer_type in ('distributor', 'wholesaler', 'retailer', 'other')),
  other_type           text,
  company_or_name      text not null,
  representative_name  text not null,
  email                text not null,
  phone                text not null,
  quantity_kg          text,
  message              text,
  gstin                text not null,
  status               text not null default 'new' check (status in ('new', 'contacted', 'closed')),
  notes                text,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);

-- ---------------------------------------------------------------- analytics
-- Filled only for visitors who accepted analytics cookies.
create table if not exists visitors (
  visitor_id    text primary key,
  visitor_no    bigint generated by default as identity unique,
  first_seen_at timestamptz not null default now(),
  last_seen_at  timestamptz not null default now()
);

create table if not exists visitor_sessions (
  id               uuid primary key default gen_random_uuid(),
  visitor_id       text not null,
  session_id       text not null unique,
  referrer         text,
  utm_source       text,
  utm_medium       text,
  utm_campaign     text,
  user_agent       text,
  device_type      text,
  browser          text,
  os               text,
  screen_width     int,
  screen_height    int,
  ip_prefix        text,
  country          text,
  region           text,
  city             text,
  started_at       timestamptz not null default now(),
  last_seen_at     timestamptz not null default now(),
  total_seconds    int not null default 0,
  page_count       int not null default 0,
  created_at       timestamptz not null default now()
);
create index if not exists visitor_sessions_started on visitor_sessions (started_at desc);
create index if not exists visitor_sessions_visitor on visitor_sessions (visitor_id);

create table if not exists visitor_pageviews (
  id                 uuid primary key default gen_random_uuid(),
  session_id         text not null references visitor_sessions (session_id) on delete cascade,
  path               text not null,
  entered_at         timestamptz not null default now(),
  seconds_on_page    int not null default 0,
  max_scroll_percent int check (max_scroll_percent between 0 and 100)
);
create index if not exists visitor_pageviews_entered on visitor_pageviews (entered_at desc);
create index if not exists visitor_pageviews_session on visitor_pageviews (session_id);

create table if not exists visitor_events (
  id           uuid primary key default gen_random_uuid(),
  session_id   text not null references visitor_sessions (session_id) on delete cascade,
  visitor_id   text not null,
  event_type   text not null check (event_type in ('product_view', 'add_to_cart', 'remove_from_cart', 'begin_checkout', 'purchase')),
  product_slug text,
  variant_kg   numeric,
  quantity     int,
  value_inr    numeric(12, 2),
  order_ref    text,
  metadata     jsonb,
  occurred_at  timestamptz not null default now(),
  created_at   timestamptz not null default now()
);
create index if not exists visitor_events_occurred on visitor_events (occurred_at desc);

create table if not exists visitor_interactions (
  id             uuid primary key default gen_random_uuid(),
  session_id     text not null references visitor_sessions (session_id) on delete cascade,
  visitor_id     text not null,
  kind           text not null check (kind in ('click', 'rage_click', 'dead_click')),
  path           text not null,
  selector       text,
  label          text,
  tag            text,
  rel_x          numeric,
  abs_y          int,
  viewport_width int,
  doc_height     int,
  click_count    int,
  occurred_at    timestamptz not null default now()
);
create index if not exists visitor_interactions_path on visitor_interactions (path, occurred_at desc);
create index if not exists visitor_interactions_kind on visitor_interactions (kind, occurred_at desc);

-- --------------------------------------------------------------------- blog
create table if not exists blog_posts (
  id              uuid primary key default gen_random_uuid(),
  slug            text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  title           text not null,
  excerpt         text,
  content_md      text not null default '',
  cover_path      text,              -- 'img/<id>' for an image stored below
  cover_alt       text,
  author_email    text,              -- the staff member who wrote it
  author_name     text not null,
  status          text not null default 'draft' check (status in ('draft', 'published')),
  published_at    timestamptz,
  reading_minutes int,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  check (status <> 'published' or published_at is not null)
);
create index if not exists blog_posts_live on blog_posts (status, published_at desc);

-- Cover images, served by the website itself (/api/blog/images/<id>).
create table if not exists blog_images (
  id            uuid primary key default gen_random_uuid(),
  content_type  text not null,
  data          bytea not null,
  created_at    timestamptz not null default now()
);
